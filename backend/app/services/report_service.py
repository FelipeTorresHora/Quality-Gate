from pydantic import ValidationError

from app.models.analysis_run import AnalysisRun
from app.services.agent.schemas import (
    AIReviewGenerated,
    AIReviewPartial,
    parse_ai_review_snapshot,
)
from app.services.evidence_redaction_service import redact_text

GITHUB_COMMENT_MARKER_TEMPLATE = "<!-- ai-quality-gate:analysis-run:{analysis_run_id} -->"


def build_final_report(run: AnalysisRun, ai_review_json: dict) -> str:
    if run.status.value == "error" and run.decision is None:
        return build_operational_error_report(run)

    decision = run.decision.value.upper() if run.decision else "NO DECISION"
    if run.decision and run.decision.value == "fail":
        outcome_note = (
            "This is a **quality-gate fail**. Gates finished and at least one "
            "policy was not met (for example coverage below the threshold). "
            "This is not an operational error."
        )
    elif run.decision and run.decision.value == "pass":
        outcome_note = (
            "This is a **quality-gate pass**. Required gates completed and met "
            "their configured policies. This is not an operational error."
        )
    else:
        outcome_note = "No Gate Decision was recorded for this Analysis Run."
    lines = [
        f"# AI Quality Gate: {decision}",
        "",
        outcome_note,
        "",
        f"**Gate Decision:** {decision}",
    ]
    if run.score is not None:
        lines.extend(["", f"**Score:** {int(run.score)}/100"])

    snapshot = _parsed_review(ai_review_json)
    summary = _summary_for(run, ai_review_json, snapshot)
    lines.extend(["", "## Summary", "", summary])
    insights = _pillar_insights(snapshot, ai_review_json)
    lines.extend(
        _pillar_section(
            "Coverage",
            run.coverage_result_json,
            ai_review_json.get("coverage_assessment"),
            None if insights is None else insights.coverage,
            show_missing_insight=insights is not None,
        )
    )
    lines.extend(
        _pillar_section(
            "Security",
            run.security_result_json,
            ai_review_json.get("security_assessment"),
            None if insights is None else insights.security,
            show_missing_insight=insights is not None,
        )
    )
    lines.extend(
        _pillar_section(
            "Technical Debt",
            run.technical_debt_result_json,
            ai_review_json.get("technical_debt_assessment"),
            None if insights is None else insights.technical_debt,
            show_missing_insight=insights is not None,
        )
    )
    lines.extend(_code_review_section(snapshot))
    lines.extend(_list_section("Blocking Reasons", _blocking_reasons(run, ai_review_json)))
    lines.extend(_list_section("Suggestions", _suggestions(run, ai_review_json)))
    lines.extend(_context_budget_section(snapshot))
    lines.extend(["", "---", "Generated by PR Quality Gate Dashboard."])
    return "\n".join(lines).strip() + "\n"


def build_operational_error_report(run: AnalysisRun) -> str:
    lines = [
        "# AI Quality Gate: OPERATIONAL ERROR",
        "",
        "This is **not** a quality-gate fail. A command, timeout, or missing "
        "report stopped execution, so there is **no Gate Decision** for this "
        "Pull Request.",
        "",
        "**Run Status:** error",
        "**Gate Decision:** none",
        "",
        "## Summary",
        "",
        run.error_message or "A required gate could not complete (command, timeout, or missing report).",
        "",
        "## Coverage",
        "",
        _snapshot_summary(run.coverage_result_json),
        "",
        "## Security",
        "",
        _snapshot_summary(run.security_result_json),
        "",
        "## Technical Debt",
        "",
        _snapshot_summary(run.technical_debt_result_json),
        "",
        "---",
        "Generated by PR Quality Gate Dashboard.",
    ]
    return "\n".join(lines).strip() + "\n"


def build_github_comment_body(run: AnalysisRun) -> str:
    marker = GITHUB_COMMENT_MARKER_TEMPLATE.format(analysis_run_id=run.id)
    report = run.final_report_markdown or build_final_report(run, run.ai_review_json)
    return f"{marker}\n\n{redact_text(report)}"


def github_comment_marker(run: AnalysisRun) -> str:
    return GITHUB_COMMENT_MARKER_TEMPLATE.format(analysis_run_id=run.id)


def _summary_for(run: AnalysisRun, ai_review_json: dict, snapshot) -> str:
    if isinstance(snapshot, AIReviewPartial):
        note = "AI review is partial because the context budget was exhausted."
        summary = snapshot.summary.strip()
        if summary:
            return f"{note} {summary}"
        return note
    if isinstance(snapshot, AIReviewGenerated) and snapshot.summary:
        return snapshot.summary
    if ai_review_json.get("status") == "generated" and ai_review_json.get("summary"):
        return str(ai_review_json["summary"])
    if ai_review_json.get("status") == "skipped":
        return "AI review was skipped, so this report summarizes deterministic gate evidence."
    if ai_review_json.get("status") == "error":
        return "AI review could not be generated, so this report summarizes deterministic gate evidence."
    if run.decision and run.decision.value == "pass":
        return "All required gates completed and passed their configured policies."
    return "One or more required gates completed and failed their configured policies."


def _parsed_review(ai_review_json: dict):
    try:
        return parse_ai_review_snapshot(ai_review_json)
    except ValidationError:
        return None


def _pillar_insights(snapshot, ai_review_json: dict):
    if isinstance(snapshot, AIReviewPartial):
        return snapshot.pillar_insights
    if isinstance(snapshot, AIReviewGenerated) and "pillar_insights" in ai_review_json:
        return snapshot.pillar_insights
    return None


def _pillar_section(
    title: str,
    snapshot: dict,
    assessment: str | None,
    insight=None,
    *,
    show_missing_insight: bool = False,
) -> list[str]:
    lines = ["", f"## {title}", "", assessment or _snapshot_summary(snapshot)]
    reasons = _string_list(snapshot.get("blocking_reasons"))
    if reasons:
        lines.extend(["", "Blocking reasons:"])
        lines.extend(f"- {reason}" for reason in reasons)
    suggestions = _string_list(snapshot.get("suggestions"))
    if suggestions:
        lines.extend(["", "Suggestions:"])
        lines.extend(f"- {suggestion}" for suggestion in suggestions)
    lines.extend(_insight_lines(insight, show_missing_insight=show_missing_insight))
    return lines


def _insight_lines(insight, *, show_missing_insight: bool) -> list[str]:
    if insight is None:
        if show_missing_insight:
            return ["", "AI insight: not reviewed."]
        return []
    lines = ["", f"AI insight: {insight.summary}"]
    assessment = _insight_assessment(insight)
    if assessment:
        lines.extend(["", assessment])
    findings = list(getattr(insight, "findings", []) or [])
    if findings:
        lines.extend(["", "AI findings:"])
        for finding in findings:
            lines.append(f"- {_finding_label(finding)}")
    alerts = list(getattr(insight, "triaged_alerts", []) or [])
    if alerts:
        lines.extend(["", "Triaged alerts:"])
        for alert in alerts:
            lines.append(f"- {alert.disposition}: {alert.title}: {alert.rationale}")
    return lines


def _insight_assessment(insight) -> str:
    for name in (
        "coverage_assessment",
        "security_assessment",
        "technical_debt_assessment",
    ):
        value = getattr(insight, name, None)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""


def _finding_label(finding) -> str:
    if finding.file_path and finding.line_number:
        location = f" ({finding.file_path}:{finding.line_number})"
    elif finding.file_path:
        location = f" ({finding.file_path})"
    else:
        location = ""
    return f"{finding.title}{location}: {finding.description}"


def _code_review_section(snapshot) -> list[str]:
    comments = []
    if isinstance(snapshot, (AIReviewGenerated, AIReviewPartial)):
        comments = list(snapshot.inline_comments)
    if not comments and not isinstance(snapshot, AIReviewPartial):
        return []
    lines = ["", "## Code Review", ""]
    if not comments:
        lines.append("None.")
        return lines
    for comment in comments:
        lines.append(
            f"- **{comment.file_path}:{comment.line_number}** "
            f"({comment.severity.value}) {comment.title}: {comment.body}"
        )
        if comment.suggestion_code:
            lines.append(f"  Suggestion: `{comment.suggestion_code}`")
    return lines


def _context_budget_section(snapshot) -> list[str]:
    budget = getattr(snapshot, "context_budget", None)
    partial = isinstance(snapshot, AIReviewPartial)
    if budget is None:
        return []
    if not partial and not budget.review_truncated and not budget.skipped_files:
        return []
    lines = [
        "",
        "## Context budget",
        "",
        f"Batches sent: {budget.batches_sent} of {budget.batches_total}.",
        f"Review truncated: {'yes' if budget.review_truncated else 'no'}",
    ]
    if budget.review_truncated or budget.skipped_files:
        lines.extend(["", "Skipped files:"])
        if budget.skipped_files:
            lines.extend(f"- `{path}`" for path in budget.skipped_files)
        else:
            lines.append("None.")
    return lines


def _snapshot_summary(snapshot: dict) -> str:
    if not snapshot:
        return "No snapshot was produced."
    status = snapshot.get("status", "not reported")
    details = [f"Status: {status}."]
    for key in (
        "total_coverage",
        "base_coverage",
        "pr_coverage",
        "changed_files_coverage",
        "coverage_drop",
        "critical",
        "high",
        "medium",
        "low",
        "score",
    ):
        if key in snapshot:
            details.append(f"{key}: {snapshot[key]}.")
    return " ".join(details)


def _blocking_reasons(run: AnalysisRun, ai_review_json: dict) -> list[str]:
    reasons = _string_list(ai_review_json.get("blocking_reasons"))
    for snapshot in (
        run.coverage_result_json,
        run.security_result_json,
        run.technical_debt_result_json,
    ):
        reasons.extend(_string_list(snapshot.get("blocking_reasons")))
    for finding in run.findings:
        if finding.blocking:
            reasons.append(finding.title)
    return _unique(reasons)


def _suggestions(run: AnalysisRun, ai_review_json: dict) -> list[str]:
    suggestions = _string_list(ai_review_json.get("suggestions"))
    for snapshot in (
        run.coverage_result_json,
        run.security_result_json,
        run.technical_debt_result_json,
    ):
        suggestions.extend(_string_list(snapshot.get("suggestions")))
    return _unique(suggestions)


def _list_section(title: str, values: list[str]) -> list[str]:
    lines = ["", f"## {title}", ""]
    if not values:
        return lines + ["None."]
    return lines + [f"- {value}" for value in values]


def _string_list(value) -> list[str]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, str)]


def _unique(values: list[str]) -> list[str]:
    seen = set()
    unique_values = []
    for value in values:
        if value not in seen:
            seen.add(value)
            unique_values.append(value)
    return unique_values
